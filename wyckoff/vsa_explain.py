# 方向 → 简短符号 (结论区/表格用)
DIR_SYMBOL = {"偏多": "▲", "偏空": "▼", "中性": "·"}

# 解释字段里以"标签词:"开头的冗余前缀 (用于剥离, 避免与 VSA_CN 重复)
_MEANING_PREFIXES = (
    "强势需求:", "强势供给:", "无需求:", "无供给:", "停止量:", "上冲量:",
    "弹簧量:", "诱多陷阱:", "诱空陷阱:", "吸收:", "性质变化:", "二次测试:",
    "努力上涨:", "努力下跌:", "卖出高潮:", "买入高潮:", "努力无结果(上涨):",
    "努力无结果(下跌):",
)


def meaning_pure(meaning: str) -> str:
    """去掉含义文本开头与标签中文名重复的前缀 (如 "强势需求: ..." → "...")。"""
    for p in _MEANING_PREFIXES:
        if meaning.startswith(p):
            return meaning[len(p):]
    return meaning


def explain(label: str) -> dict:
    """返回某标签的完整解释 dict; 未知标签返回 None。"""
    return VSA_EXPLAIN.get(label) or EVENT_EXPLAIN.get(label)


def explain_lines(label: str) -> list:
    """返回某标签的解释为文本行列表 (结论区/弹窗共用)。"""
    e = VSA_EXPLAIN.get(label) or EVENT_EXPLAIN.get(label)
    if not e:
        return [f"未收录信号 {label} 的解释"]
    return [
        f"含义: {meaning_pure(e['meaning'])}",
        f"方向: {e['direction']}",
        f"关注: {e['watch']}",
        f"建议: {e['advice']}",
        f"流程: {e['role']}",
        f"失效: {e['fail']}",
    ]


def explain_summary(label: str) -> str:
    """一行摘要: 方向符号 + 含义前段 (信号列表悬浮提示用)。"""
    e = VSA_EXPLAIN.get(label) or EVENT_EXPLAIN.get(label)
    if not e:
        return label
    return f"{DIR_SYMBOL.get(e['direction'], '·')} {meaning_pure(e['meaning'])}"
